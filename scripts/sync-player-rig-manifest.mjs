import { NodeIO } from '@gltf-transform/core';
import { EXTTextureWebP, KHRMeshQuantization } from '@gltf-transform/extensions';
import { access, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { classifyRunnerMotionQuality } from './player-motion-quality-policy.mjs';
import { getRigProfileForKey, missingNamedPartGroups } from '../src/replay3d/assets/playerRigAcceptance.js';
import { PLAYER_RIG_ASSETS } from '../src/replay3d/assets/playerRigManifest.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src', 'replay3d', 'assets', 'generatedPlayerRigAvailability.js');
const retargetReportPath = path.join(root, 'asset-inbox', 'players', 'generated', 'blender-normalize-report.json');
const io = new NodeIO().registerExtensions([EXTTextureWebP, KHRMeshQuantization]);

function toDiskPath(assetUrl) {
  return path.join(root, 'public', assetUrl.replace(/^\//, '').replaceAll('/', path.sep));
}

async function exists(file) {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

function getSceneStats(doc) {
  const rootDoc = doc.getRoot();
  const clips = rootDoc.listAnimations().map((animation) => animation.getName()).filter(Boolean);
  const meshes = rootDoc.listMeshes();
  const nodes = rootDoc.listNodes().map((node) => node.getName()).filter(Boolean);
  const meshNames = meshes.map((mesh) => mesh.getName()).filter(Boolean);
  const materialNames = rootDoc.listMaterials().map((material) => material.getName()).filter(Boolean);
  const uploadedVertices = meshes.reduce((sum, mesh) => (
    sum + mesh.listPrimitives().reduce((innerSum, primitive) => {
      const position = primitive.getAttribute('POSITION');
      return innerSum + (position?.getCount() ?? 0);
    }, 0)
  ), 0);

  return {
    clips,
    namedParts: [...meshNames, ...nodes, ...materialNames],
    uploadedVertices,
  };
}

async function loadRunnerRetargetTargets() {
  try {
    const report = JSON.parse(await readFile(retargetReportPath, 'utf8'));
    return new Map((report.targets ?? [])
      .filter((target) => target.profile === 'runner' && target.key)
      .map((target) => [target.key, target]));
  } catch {
    return new Map();
  }
}

function getRetargetQualitySummary(key, profile, retargetTargets) {
  if (!key.startsWith('runner')) return null;

  const target = retargetTargets.get(key);
  if (!target) {
    return {
      status: 'missing-retarget-report',
      isFinalGrade: false,
      finalGradeClipNames: [],
      missingFinalGradeClipNames: profile.requiredClips,
    };
  }

  const quality = classifyRunnerMotionQuality(target.motionSourceClips, {
    requiredClipNames: profile.requiredClips,
  });

  return {
    status: quality.status,
    isFinalGrade: quality.isFinalGrade,
    finalGradeClipNames: quality.finalGradeClipNames,
    missingFinalGradeClipNames: quality.missingFinalGradeClipNames,
  };
}

async function inspectProductionAsset(key, url, retargetTargets) {
  const file = toDiskPath(url);
  if (!(await exists(file))) {
    return {
      available: false,
      url,
      clips: [],
      bytes: 0,
      uploadedVertices: 0,
    };
  }

  const fileStat = await stat(file);
  const doc = await io.read(file);
  const stats = getSceneStats(doc);
  const profile = getRigProfileForKey(key);
  const retargetQuality = getRetargetQualitySummary(key, profile, retargetTargets);
  const hasRequiredClips = profile.requiredClips.every((clip) => stats.clips.includes(clip));
  const missingPartGroups = missingNamedPartGroups(stats.namedParts, profile.requiredNamedPartGroups);
  const withinByteBudget = fileStat.size <= profile.maxBytes;

  return {
    available: hasRequiredClips
      && stats.uploadedVertices <= profile.maxVertices
      && withinByteBudget
      && missingPartGroups.length === 0,
    url,
    clips: stats.clips,
    bytes: fileStat.size,
    missingPartGroups,
    retargetMotionQuality: retargetQuality?.status ?? null,
    isFinalGradeMotion: retargetQuality?.isFinalGrade ?? false,
    finalGradeClips: retargetQuality?.finalGradeClipNames ?? [],
    missingFinalGradeClips: retargetQuality?.missingFinalGradeClipNames ?? [],
    uploadedVertices: stats.uploadedVertices,
  };
}

const production = {};
const retargetTargets = await loadRunnerRetargetTargets();
for (const [key, url] of Object.entries({
  runnerHome: PLAYER_RIG_ASSETS.productionTargets.runnerHome,
  runnerAway: PLAYER_RIG_ASSETS.productionTargets.runnerAway,
  goalieHome: PLAYER_RIG_ASSETS.productionTargets.goalieHome,
  goalieAway: PLAYER_RIG_ASSETS.productionTargets.goalieAway,
})) {
  production[key] = await inspectProductionAsset(key, url, retargetTargets);
}

const serialized = `${[
  '// Generated by scripts/sync-player-rig-manifest.mjs.',
  '// Commit this file so the browser runtime never tries to fetch missing production GLBs.',
  'export const PLAYER_RIG_AVAILABILITY = ',
].join('\n')}${JSON.stringify({ production }, null, 2)};\n\nexport const HAS_FULL_PRODUCTION_RIG_SET = Object.values(PLAYER_RIG_AVAILABILITY.production)\n  .every((asset) => asset.available);\n\nexport const HAS_RUNNER_PRODUCTION_RIG_SET = PLAYER_RIG_AVAILABILITY.production.runnerHome.available\n  && PLAYER_RIG_AVAILABILITY.production.runnerAway.available;\n`;

let current = '';
try {
  current = await readFile(outputPath, 'utf8');
} catch {
  current = '';
}

if (current !== serialized) {
  await writeFile(outputPath, serialized);
  console.log(`Updated ${path.relative(root, outputPath)}`);
} else {
  console.log(`${path.relative(root, outputPath)} already up to date`);
}
