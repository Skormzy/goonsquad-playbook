function opponent(id, x, y, label, hasBall = false) {
  return {
    id,
    x,
    y,
    l: label,
    ...(hasBall ? { hasBall: true } : {}),
  };
}

function opponentGoalie(x = 50, y = 93) {
  return opponent('og', x, y, 'G');
}

